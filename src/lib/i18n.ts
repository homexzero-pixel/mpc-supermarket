export type MsgKey = keyof (typeof dict)['en'];
export function t(lang: Lang, key: MsgKey): string {
  return (dict[lang] as Record<string, string>)[key] ?? dict.en[key];
}
export function clientStrings(lang: Lang) {
  return dict[lang];
}
export function pickName(lang: Lang, en: string, ta?: string | null) {
  return lang === 'ta' && ta ? ta : en;
}
